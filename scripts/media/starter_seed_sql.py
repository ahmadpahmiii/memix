#!/usr/bin/env python3
"""Writes the sounds seed migration for the 10 starter sounds from content/starter-sounds/manifest.json (P3-13).

    python3 -I scripts/media/starter_seed_sql.py > supabase/migrations/<stamp>_seed_starter_sounds.sql

Reproducible: same manifest, same output. The Storage key of each sound is sounds/<yyyy>/<mm>/<id>.m4a; upload_media.py
--starters derives the same key from the same constant, so rows and files cannot drift apart.
Category and tags are catalog decisions (the manifest has neither); change them here, not in the SQL.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KEY_YEAR_MONTH = "2026/11"  # when the files are first uploaded; keys never change afterwards

CATALOG = {  # slug: (category_id, tags)
    "sad-trombone": ("sound_fails", ["fail", "sad", "trombone", "womp womp"]),
    "record-scratch": ("sound_reactions", ["record scratch", "freeze frame", "wait what"]),
    "boing": ("sound_cartoon", ["boing", "spring", "bounce"]),
    "sitcom-laugh": ("sound_reactions", ["laugh", "sitcom", "laugh track"]),
    "whoosh": ("sound_impacts", ["whoosh", "swish", "transition"]),
    "deep-boom": ("sound_impacts", ["boom", "bass drop", "impact"]),
    "awkward-crickets": ("sound_reactions", ["crickets", "awkward", "silence"]),
    "wrong-buzzer": ("sound_fails", ["buzzer", "wrong", "nope"]),
    "cartoon-fall": ("sound_cartoon", ["fall", "slide whistle", "cartoon"]),
    "drum-roll": ("sound_suspense", ["drum roll", "rimshot", "reveal"]),
}


def sql(text):
    return "'" + text.replace("'", "''") + "'"


def main():
    manifest = json.loads((ROOT / "content/starter-sounds/manifest.json").read_text(encoding="utf-8"))
    rows = []
    for s in manifest["sounds"]:
        slug = s["file"].removesuffix(".m4a")
        category, tags = CATALOG[slug]
        assert s["licenseType"] != "CC-BY" or s["credit"], slug
        title = json.dumps(s["title"], ensure_ascii=False, separators=(",", ":"))
        tag_list = "array[" + ", ".join(sql(t) for t in tags) + "]"
        credit = sql(s["credit"]) if s["credit"] else "null"
        key = f"sounds/{KEY_YEAR_MONTH}/{s['id']}.m4a"
        rows.append(
            f"  ({sql(s['id'])}, {sql(title)}::jsonb, {sql(category)}, '{{global}}', {tag_list},\n"
            f"   {sql(key)}, {s['durationMs']}, null,\n"
            f"   {sql(s['sourceUrl'])}, {sql(s['licenseType'])}, {sql(s['licenseProof'])}, {credit}, 'owner')"
        )
    print("-- P3-13 seed: the 10 owner-approved starter sounds (approved 8 Oct 2026; docs/pm/decision-log.md).")
    print("-- Generated by scripts/media/starter_seed_sql.py from content/starter-sounds/manifest.json. The ids are the")
    print("-- manifest ids (uuid5 of the Freesound URL), so projects that use a bundled starter sound keep working.")
    print("-- Titles in id, es, pt and hi are machine drafts until P5-06. Files: upload_media.py --starters (same keys).")
    print("-- The rows are active once applied: apply the bucket migration, upload the files, then apply this seed.")
    print("insert into public.sounds (id, title, category_id, regions, tags, file_path, duration_ms, waveform_path,")
    print("                           source_url, license_type, license_proof, credit, added_by)")
    print("values")
    print(",\n".join(rows))
    print("on conflict (id) do nothing;")


if __name__ == "__main__":
    sys.exit(main())
